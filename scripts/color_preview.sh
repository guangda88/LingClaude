#!/usr/bin/env bash
# 用户回显行配色预览 v2 —— 在真实终端里跑：bash scripts/color_preview.sh
# v2 依据：用户实测排除 11 码（30/34/35/90/1;90/1;95/47/102/103/106/107）
#   → 推断深色终端：深色系文字沉底、裸背景码配默认前景(浅色)浅底浅字隐形
#   → v2 全部为「显式配对」组合：白字配深底 / 黑字配浅底
#   → 已剔除：品红全系(35/45/95/105/1;95)、1;96(撞模型回复亮青)、用户排除码
S="🧑 用户: 这是用户命令回显行的样子"

echo "════════ A. 显式配对·背景块（v1 翻车区的修正版，最推荐先看） ════════"
printf "  \033[1;97;44m%s\033[0m   ← 白字蓝底 1;97;44\n" "$S"
printf "  \033[1;97;42m%s\033[0m   ← 白字绿底 1;97;42\n" "$S"
printf "  \033[1;97;100m%s\033[0m   ← 白字灰底 1;97;100\n" "$S"
printf "  \033[1;30;47m%s\033[0m   ← 黑字白底 1;30;47\n" "$S"
