#!/usr/bin/env bash
# 用户回显行配色预览 v3 —— 在真实终端里跑：bash scripts/color_preview.sh
# v3 变更：彻底删除已排除码（v2 的 D 区删除线参考区整体移除——终端不支持 SGR 9 时渲染成素字，观感即"没清掉"）
# 排除名单（永久，不再出现在本脚本）：30 34 35 90 "1;90" "1;95" 47 102 103 106 107
#   另排除：品红全系(35/45/95/105)、1;96（与模型回复亮青撞车）
# 剩余候选全部为「显式配对」：白字配深底 / 黑字配浅底（适配深色背景终端）
S="🧑 用户: 这是用户命令回显行的样子"

echo "════════ A. 显式配对·背景块（最推荐先看） ════════"
printf "  \033[1;97;44m%s\033[0m   ← 白字蓝底 1;97;44\n" "$S"
printf "  \033[1;97;42m%s\033[0m   ← 白字绿底 1;97;42\n" "$S"
printf "  \033[1;97;100m%s\033[0m   ← 白字灰底 1;97;100\n" "$S"
printf "  \033[1;30;47m%s\033[0m   ← 黑字白底 1;30;47\n" "$S"
printf "  \033[1;30;43m%s\033[0m   ← 黑字黄底 1;30;43\n" "$S"
printf "  \033[1;97;41m%s\033[0m   ← 白字红底 1;97;41（注意与✗错误语义撞车）\n" "$S"

echo ""
echo "════════ B. 反显系（当前采用 7;1） ════════"
printf "  \033[7;1m%s\033[0m   ← 反显+粗体 7;1（当前实际）\n" "$S"
printf "  \033[7;4m%s\033[0m   ← 反显+下划线 7;4\n" "$S"
printf "  \033[1;4;7m%s\033[0m   ← 反显+粗体+下划线 1;4;7\n" "$S"

echo ""
echo "════════ C. 亮前景+粗体（无底色） ════════"
printf "  \033[1;97m%s\033[0m   ← 亮白粗体 1;97\n" "$S"
printf "  \033[1;93m%s\033[0m   ← 亮黄粗体 1;93（与⚠警告同色系）\n" "$S"
printf "  \033[1;91m%s\033[0m   ← 亮红粗体 1;91（与✗错误语义撞车）\n" "$S"
printf "  \033[4;92m%s\033[0m   ← 亮绿+下划线 4;92（与✓成功同色系）\n" "$S"
